#!/usr/bin/env bash
# Prints the Homebrew formula for a skiff release to stdout.
#
#   scripts/homebrew-formula.sh v1.2.3 <sha256 of the darwin_arm64 archive>
#
# The release workflow writes the result to Formula/skiff.rb in
# sovyn-eu/homebrew-tap. SKIFF_ARCHIVE_URL overrides the download URL, so the
# formula can be tried against a local `make dist` (file:///...).
set -euo pipefail

usage() {
	echo "usage: $0 <tag vX.Y.Z> <sha256>" >&2
	exit 2
}

[[ $# -eq 2 ]] || usage
tag=$1
sha=$2

if [[ ! $tag =~ ^v[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z.]+)?$ ]]; then
	echo "$0: '$tag' is not a release tag like v1.2.3" >&2
	exit 2
fi
if [[ ! $sha =~ ^[0-9a-f]{64}$ ]]; then
	echo "$0: '$sha' is not a sha256 hex digest" >&2
	exit 2
fi

archive="skiff_${tag}_darwin_arm64.tar.gz"
url=${SKIFF_ARCHIVE_URL:-https://github.com/sovyn-eu/skiff/releases/download/${tag}/${archive}}

cat <<EOF
# Generated by the release workflow of sovyn-eu/skiff; edits here are
# overwritten by the next release. Source: scripts/homebrew-formula.sh
class Skiff < Formula
  desc "Throwaway Linux VMs on Apple Silicon, one per task or coding agent"
  homepage "https://github.com/sovyn-eu/skiff"
  url "${url}"
  sha256 "${sha}"
  license "Apache-2.0"

  depends_on arch: :arm64
  depends_on macos: :tahoe

  def install
    bin.install "skiff"
    generate_completions_from_executable(bin/"skiff", "completion")
  end

  def caveats
    <<~EOS
      Run this once to install Apple's container CLI and set up the host:
        skiff prepare
    EOS
  end

  test do
    assert_match "skiff version v#{version}", shell_output("#{bin}/skiff --version")
  end
end
EOF
